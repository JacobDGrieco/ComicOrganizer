"""Seed the comic-run research/download queue without importing issues."""

from __future__ import annotations

import argparse
from dataclasses import dataclass

from db_common import connect_database


@dataclass(frozen=True)
class RunCandidate:
    id: str
    title: str
    volume: str
    years: str
    category: str
    publication_type: str
    universe_hint: str
    lead_characters: str
    priority: str
    scope_status: str
    research_status: str
    download_status: str = "Needed"
    local_run_id: str | None = None
    marvel_metadata_series_id: int | None = None
    marvel_url: str | None = None
    marvel_issue_count: int | None = None
    gcd_url: str | None = None
    notes: str | None = None


def main() -> int:
    args = parse_args()
    with connect_database(args.db) as connection:
        for candidate in CANDIDATES:
            upsert_candidate(connection, candidate)
    print(f"Seeded {len(CANDIDATES)} comic runs.")
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Seed Spider-Man comic runs.")
    parser.add_argument("--db", default="database/database.db", help="SQLite database path.")
    return parser.parse_args()


def upsert_candidate(connection, candidate: RunCandidate) -> None:
    connection.execute(
        """
		INSERT INTO comic_runs (
			id, title, volume, years, category, publication_type, universe_hint,
			lead_characters, priority, marvel_url, marvel_issue_count, notes
		)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
		ON CONFLICT(id) DO UPDATE SET
			title = excluded.title,
			volume = excluded.volume,
			years = excluded.years,
			category = excluded.category,
			publication_type = excluded.publication_type,
			universe_hint = excluded.universe_hint,
			lead_characters = excluded.lead_characters,
			priority = excluded.priority,
			marvel_url = COALESCE(excluded.marvel_url, comic_runs.marvel_url),
			marvel_issue_count = COALESCE(excluded.marvel_issue_count, comic_runs.marvel_issue_count),
			notes = excluded.notes
		""",
        (
            candidate.id,
            candidate.title,
            candidate.volume,
            candidate.years,
            candidate.category,
            candidate.publication_type,
            candidate.universe_hint,
            candidate.lead_characters,
            candidate.priority,
            candidate.marvel_url,
            candidate.marvel_issue_count,
            candidate.notes,
        ),
    )


